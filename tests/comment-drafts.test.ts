import { afterEach, describe, expect, it, vi } from 'vitest';
import { commentDraftKey, createCommentDraftStore, initializeCommentDraft, parseCommentDrafts } from '../src/lib/comment-drafts';
import { siteConfig } from '../src/config/site';

const storage = () => {
  const entries = new Map<string, string>();
  return { getItem: (key: string) => entries.get(key) ?? null, setItem: (key: string, value: string) => { entries.set(key, value); } };
};
afterEach(() => { vi.unstubAllGlobals(); vi.restoreAllMocks(); });

describe('comment body drafts', () => {
  it('preserves a submission ID through refresh while changes to other request fields start a new operation', () => {
    const memory = storage(); const key = 'anonymous/guestbook:root';
    let store = createCommentDraftStore(memory, () => 100); store.save(key, '同一正文');
    const state = { notifyReply: true, quoteMessageId: 3, quoteContent: '原评论引用片段' };
    const first = store.capture(key, '同一正文', 'a'.repeat(64), state);
    store = createCommentDraftStore(memory, () => 100);
    expect(store.submissionState(key)).toEqual(state);
    expect(store.capture(key, '同一正文', 'a'.repeat(64), state).operationId).toBe(first.operationId);
    const changedEmail = store.capture(key, '同一正文', 'b'.repeat(64));
    expect(changedEmail.operationId).not.toBe(first.operationId);
    expect(store.complete(first)).toBe(false);
    expect(store.read(key)).toBe('同一正文');
    expect(memory.getItem(siteConfig.commentDrafts.storageKey)).not.toContain('@');
  });
  it('isolates reader, anonymous, article, reply and administrator namespaces', () => {
    const memory = storage(); const store = createCommentDraftStore(memory, () => 100);
    const targets = [['anonymous', 'guestbook:root'], ['reader:1', 'guestbook:root'], ['reader:2', 'guestbook:root'], ['reader:1', 'article:2:root'], ['reader:1', 'article:2:reply:3:4']];
    targets.forEach(([identity, target], index) => store.save(commentDraftKey(identity, target), `正文${index}`));
    targets.forEach(([identity, target], index) => expect(store.read(commentDraftKey(identity, target))).toBe(`正文${index}`));
    const admin = createCommentDraftStore(memory, () => 100, `${siteConfig.commentDrafts.storageKey}:admin`);
    admin.save(commentDraftKey('admin', 'message:3:root'), '站长回复');
    expect(store.read('admin/message:3:root')).toBe('');
    expect(commentDraftKey('anonymous', 'message:3:root')).toBe('');
  });
  it.each(['另一标签正文', '原提交正文'])('keeps an unresolved operation after another tab completes %s and after refresh', (otherContent) => {
    const shared = storage(); const firstSession = storage(); const secondSession = storage();
    const key = 'anonymous/guestbook:root'; const namespace = siteConfig.commentDrafts.storageKey;
    let firstTab = createCommentDraftStore(shared, () => 100, namespace, firstSession);
    const secondTab = createCommentDraftStore(shared, () => 100, namespace, secondSession);
    firstTab.save(key, '原提交正文');
    const unresolved = firstTab.capture(key, '原提交正文', 'a'.repeat(64));
    secondTab.save(key, otherContent);
    const other = secondTab.capture(key, otherContent, (otherContent === '原提交正文' ? 'a' : 'b').repeat(64));
    expect(secondTab.complete(other)).toBe(true);
    firstTab = createCommentDraftStore(shared, () => 100, namespace, firstSession);
    firstTab.save(key, '原提交正文');
    const retried = firstTab.capture(key, '原提交正文', 'a'.repeat(64));
    expect(retried.operationId).toBe(unresolved.operationId);
    expect(firstTab.complete(retried)).toBe(true);
    firstTab.save(key, '原提交正文');
    expect(firstTab.capture(key, '原提交正文', 'a'.repeat(64)).operationId).not.toBe(unresolved.operationId);
    expect(firstSession.getItem(`${namespace}:pending`)).not.toContain('正文');
  });
  it('preserves independent pending requests across identities and targets while completing only one operation', () => {
    const memory = storage(); const pending = storage(); const namespace = siteConfig.commentDrafts.storageKey;
    const store = createCommentDraftStore(memory, () => 100, namespace, pending);
    const keys = ['anonymous/guestbook:root', 'reader:1/guestbook:root', 'reader:1/article:2:root', 'reader:1/article:2:reply:3:4'];
    const snapshots = keys.map((key) => store.capture(key, '同一正文', 'a'.repeat(64)));
    expect(new Set(snapshots.map((snapshot) => snapshot.operationId)).size).toBe(keys.length);
    store.complete(snapshots[0]);
    snapshots.slice(1).forEach((snapshot) => expect(store.capture(snapshot.key, '同一正文', 'a'.repeat(64)).operationId).toBe(snapshot.operationId));
    expect(store.capture(keys[0], '同一正文', 'a'.repeat(64)).operationId).not.toBe(snapshots[0].operationId);
  });
  it('keeps IME input after success but starts a fresh operation and stores only a digest of private request fields', async () => {
    const local = storage(); const session = storage();
    vi.stubGlobal('localStorage', local); vi.stubGlobal('sessionStorage', session);
    vi.stubGlobal('window', new EventTarget());
    vi.stubGlobal('document', Object.assign(new EventTarget(), { hidden: false, createElement: () => ({ className: '', textContent: '', setAttribute() {}, remove() {} }) }));
    const field = Object.assign(new EventTarget(), { value: '', closest: () => ({ after() {} }) }) as unknown as HTMLTextAreaElement;
    const draft = initializeCommentDraft(field, 'guestbook', null);
    field.value = '仍在输入的正文'; field.dispatchEvent(new Event('input'));
    const body = { content: field.value, nickname: '私密昵称', email: 'private@example.test', notifyReply: true };
    const original = await draft.captureSubmission(body);
    const persisted = `${local.getItem(siteConfig.commentDrafts.storageKey)}${session.getItem(`${siteConfig.commentDrafts.storageKey}:pending`)}`;
    expect(persisted).not.toContain(body.email); expect(persisted).not.toContain(body.nickname);
    field.dispatchEvent(new Event('compositionstart'));
    expect(draft.complete(original)).toBe(false); expect(field.value).toBe(body.content);
    field.dispatchEvent(new Event('compositionend'));
    const next = await draft.captureSubmission(body);
    expect(next.operationId).not.toBe(original.operationId);
    expect(draft.complete(next)).toBe(true); expect(field.value).toBe('');
    draft.destroy();
  });
  it.each(['unavailable', 'quota'])('retains same-page retry IDs when browser storage is %s', async (failure) => {
    const local = storage(); const session = storage();
    vi.stubGlobal('localStorage', failure === 'unavailable' ? { ...local, getItem() { throw new DOMException('Disabled', 'SecurityError'); } } : local);
    vi.stubGlobal('sessionStorage', session);
    vi.stubGlobal('window', new EventTarget());
    vi.stubGlobal('document', Object.assign(new EventTarget(), { hidden: false, createElement: () => ({ className: '', textContent: '', setAttribute() {}, remove() {} }) }));
    vi.spyOn(console, 'warn').mockImplementation(() => {});
    const field = Object.assign(new EventTarget(), { value: '', closest: () => ({ after() {} }) }) as unknown as HTMLTextAreaElement;
    const draft = initializeCommentDraft(field, 'guestbook', null);
    field.value = '存储不可用时仍可重试'; field.dispatchEvent(new Event('input'));
    const body = { content: field.value, email: 'private@example.test', notifyReply: true };
    const original = await draft.captureSubmission(body);
    if (failure === 'quota') vi.stubGlobal('sessionStorage', { ...session, setItem() { throw new DOMException('Full', 'QuotaExceededError'); } });
    expect((await draft.captureSubmission(body)).operationId).toBe(original.operationId);
    const changed = await draft.captureSubmission({ ...body, email: 'changed@example.test' });
    expect(changed.operationId).not.toBe(original.operationId);
    expect((await draft.captureSubmission({ ...body, email: 'changed@example.test' })).operationId).toBe(changed.operationId);
    expect(draft.complete(original)).toBe(false); expect(field.value).toBe(body.content);
    field.value = body.content; field.dispatchEvent(new Event('input'));
    expect((await draft.captureSubmission(body)).operationId).not.toBe(original.operationId);
    draft.destroy();
  });
  it('only clears the successful snapshot and keeps newer edits or another reply', () => {
    const store = createCommentDraftStore(storage(), () => 100);
    const key = 'reader:1/article:2:root';
    store.save(key, '提交时正文');
    const submitted = { key, content: store.read(key) };
    store.save(key, '等待期间继续写');
    expect(store.complete(submitted)).toBe(false);
    expect(store.read(key)).toBe('等待期间继续写');
    store.save('reader:1/article:2:reply:3:4', '另一个回复');
    expect(store.complete({ key, content: '等待期间继续写' })).toBe(true);
    expect(store.read('reader:1/article:2:reply:3:4')).toBe('另一个回复');
  });
  it('rejects invalid, expired and oversized records and never retains extra profile fields', () => {
    const key = 'anonymous/guestbook:root'; const now = 8 * 86400000;
    expect(parseCommentDrafts('{')).toEqual({});
    expect(parseCommentDrafts(JSON.stringify({ '': { content: 'bad', updatedAt: now } }), now)).toEqual({});
    expect(parseCommentDrafts(JSON.stringify({ [key]: { content: '旧草稿', updatedAt: 1 } }), now)).toEqual({});
    const store = createCommentDraftStore(storage(), () => now);
    store.save(key, '正文'); expect(store.read(key)).toBe('正文');
    expect(parseCommentDrafts(JSON.stringify({ [key]: { content: 'x'.repeat(1001), updatedAt: now } }), now)).toEqual({});
    expect(parseCommentDrafts(JSON.stringify({ [key]: { content: '正文', updatedAt: now, email: 'private@example.test' } }), now)).toEqual({ [key]: { content: '正文', updatedAt: now } });
  });
  it('restores after refresh, isolates identity switching, preserves IME and late responses', () => {
    const local = storage(); const session = storage();
    const documentTarget = Object.assign(new EventTarget(), { hidden: false, createElement: () => ({ className: '', textContent: '', setAttribute() {}, remove() {} }) });
    vi.stubGlobal('document', documentTarget); vi.stubGlobal('window', new EventTarget());
    vi.stubGlobal('localStorage', local); vi.stubGlobal('sessionStorage', session);
    const field = Object.assign(new EventTarget(), { value: '', closest: () => ({ after() {} }) }) as unknown as HTMLTextAreaElement;
    let draft = initializeCommentDraft(field, 'article:2', null);
    field.value = '匿名草稿'; field.dispatchEvent(new Event('input'));
    draft.switchTarget('article:2:reply:3:4'); field.value = '回复草稿'; field.dispatchEvent(new Event('input'));
    draft.destroy(); draft = initializeCommentDraft(field, 'article:2', null);
    expect(draft.target).toBe('article:2:reply:3:4'); expect(field.value).toBe('回复草稿');
    const submitted = draft.capture();
    draft.switchIdentity(5); expect(field.value).toBe('');
    field.value = '读者正文'; field.dispatchEvent(new Event('input'));
    expect(draft.complete(submitted)).toBe(false); expect(field.value).toBe('读者正文');
    const readerSubmitted = draft.capture(); field.dispatchEvent(new Event('compositionstart'));
    expect(draft.complete(readerSubmitted)).toBe(false); expect(field.value).toBe('读者正文');
    field.dispatchEvent(new Event('compositionend'));
    expect(draft.complete(readerSubmitted)).toBe(true); expect(field.value).toBe('');
    draft.switchIdentity(null); draft.switchTarget('article:2:root'); expect(field.value).toBe('匿名草稿');
    draft.destroy();
  });
});
